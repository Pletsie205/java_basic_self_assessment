public class CompareTwoNumbers {
    public static void main(String[] args){
        
        int number1 = 25;
        int number2 = 39;
        
        if(number1 != number2){
            
            System.out.println(number1+ "!= " + number2);
        }
        if(number1 < number2){
            
            System.out.println(number1 + " < " + number2);
        }
        if(number1 <= number2){
            
        System.out.println(number1 + " <= " + number2);
        
        }
        if(number1 > number2){
            
            System.out.println(number1 + " > " + number2);
        }
        if(number1 >= number2){
            
        System.out.println(number1 + " >= " + number2);
        
        }
        if(number1 == number2){
            
        System.out.println(number1 + " == " + number2);
        
        }
    }
}
